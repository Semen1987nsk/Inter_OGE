/**
 * Работа упругой силы и силы тяжести при подвешивании груза на пружину.
 *
 * Используется в опыте 2.4 «Измерение работы силы упругости».
 *
 * Главные формулы (см. ФИПИ ОГЭ-2026 спец., задание 17):
 *   W_упр = k · Δl² / 2  — через жёсткость
 *   W_упр = F · Δl / 2   — через максимальную силу упругости (площадь треугольника)
 *
 * При статическом подвешивании F = m·g (баланс сил), поэтому обе формулы
 * дают одинаковый результат и графически интерпретируются как площадь
 * треугольника под прямой F(Δl).
 *
 * Дополнительная физика для расширенного результата:
 *   A_грав = m · g · Δl  — работа силы тяжести при опускании груза
 *
 * При статическом подвесе A_грав = 2 · W_упр: половина работы силы тяжести
 * запасается в пружине, половина переходит в кинетическую энергию груза
 * (если он отпущен) или поглощается рукой (если опускается медленно).
 * Это важный методический инсайт для ОГЭ-2026: даёт ученику понять, почему
 * пружина не «поглощает» всю работу силы тяжести.
 *
 * Все функции pure, без зависимостей от DOM.
 */

import { G } from '@/types/spring';

/**
 * Работа упругой силы через жёсткость: W = k · Δl² / 2.
 *
 * @param k_Npm   жёсткость пружины [Н/м]
 * @param dl_cm   удлинение [см]
 * @returns       работа упругой силы [Дж]
 *
 * @throws RangeError при k ≤ 0
 *
 * @example
 *   workFromStiffness(50, 1.96) // ≈ 0.00961 Дж (m=100 г, k=50)
 *   workFromStiffness(50, 3.92) // ≈ 0.0384 Дж — в 4 раза больше при удвоении Δl
 */
export function workFromStiffness(k_Npm: number, dl_cm: number): number {
  if (k_Npm <= 0) {
    throw new RangeError(`Жёсткость пружины должна быть > 0, получено: ${k_Npm}`);
  }
  const dl_m = dl_cm / 100;
  return 0.5 * k_Npm * dl_m * dl_m;
}

/**
 * Работа упругой силы через максимальную силу: W = F · Δl / 2.
 * Геометрически — площадь треугольника под прямой F(Δl) на отрезке [0, Δl].
 *
 * @param F_max_N   максимальная сила упругости [Н] (= m·g для статики)
 * @param dl_cm     удлинение [см]
 * @returns         работа упругой силы [Дж]
 *
 * @example
 *   workFromForce(0.98, 1.96) // ≈ 0.00961 Дж — то же, что и через k=50
 */
export function workFromForce(F_max_N: number, dl_cm: number): number {
  const dl_m = dl_cm / 100;
  return 0.5 * F_max_N * dl_m;
}

/**
 * Работа силы тяжести при опускании груза на расстояние Δl: A = m·g·Δl.
 *
 * При статическом подвесе на пружину A_грав = 2 · W_упр: половина запасается
 * в пружине, половина — в кинетической энергии груза или поглощается рукой.
 *
 * @param massGrams   масса груза [г]
 * @param dl_cm       расстояние опускания [см]
 * @param g           ускорение свободного падения [м/с²], по умолчанию 9.8 (РФ-школа)
 * @returns           работа силы тяжести [Дж]
 *
 * @example
 *   workOfGravity(100, 1.96) // ≈ 0.0192 Дж — ровно в 2 раза больше W_упр
 */
export function workOfGravity(massGrams: number, dl_cm: number, g: number = G): number {
  const m_kg = massGrams / 1000;
  const dl_m = dl_cm / 100;
  return m_kg * g * dl_m;
}

/**
 * Проверка совместности двух способов вычислить W_упр (через k и через F).
 * Используется в журнале — если значения расходятся больше допуска, ученик
 * допустил ошибку при ручном вводе или неправильно снял показания шкалы.
 *
 * @param W_via_k     W = k·Δl²/2 [Дж]
 * @param W_via_F     W = F·Δl/2 [Дж]
 * @param tolerance   относительный допуск (по умолчанию 5% — стандарт ФИПИ)
 * @returns           true если значения совпадают в пределах допуска
 */
export function isElasticWorkConsistent(
  W_via_k: number,
  W_via_F: number,
  tolerance: number = 0.05,
): boolean {
  const max = Math.max(Math.abs(W_via_k), Math.abs(W_via_F));
  if (max === 0) return W_via_k === 0 && W_via_F === 0;
  return Math.abs(W_via_k - W_via_F) / max <= tolerance;
}

/**
 * Округление значения работы для отображения в журнале.
 * 5 знаков после запятой — типичные значения 0.001-0.1 Дж в школьном опыте.
 */
export function formatWork(W_J: number): string {
  if (Math.abs(W_J) < 0.0001) return '0.0000';
  return W_J.toFixed(4);
}
